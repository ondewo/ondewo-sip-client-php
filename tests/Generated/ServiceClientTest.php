<?php

declare(strict_types=1);

namespace Ondewo\Sip\Tests\Generated;

use Grpc\BaseStub;
use Grpc\ChannelCredentials;
use Ondewo\Sip\Auth\BearerTokenAuthenticator;
use Ondewo\Sip\SipClient;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use ReflectionMethod;

/**
 * Constructs the generated service stubs against a dummy target. gRPC channels connect lazily, so
 * nothing here touches the network - but the stub, its channel options and its method surface are
 * all real.
 *
 * PRODUCT-SPECIFIC: ondewo-sip-api declares a single service, `ondewo.sip.Sip`, and every one of
 * its RPCs is unary - there is no client-, server- or bidirectional-streaming method anywhere in
 * the api, so the streaming case of the pilot suite (ondewo-nlu-client-php) was dropped rather
 * than faked.
 */
final class ServiceClientTest extends TestCase
{
    private const DUMMY_TARGET = 'localhost:50051';

    /**
     * Every RPC of ondewo.sip.Sip.
     */
    private const UNARY_METHOD_COUNT = 11;

    /**
     * @var list<BaseStub>
     */
    private array $openClients = [];

    protected function tearDown(): void
    {
        foreach ($this->openClients as $client) {
            $client->close();
        }
        $this->openClients = [];

        parent::tearDown();
    }

    public function testAServiceClientIsConstructedAgainstAnInsecureChannel(): void
    {
        $client = $this->open(new SipClient(self::DUMMY_TARGET, [
            'credentials' => ChannelCredentials::createInsecure(),
        ]));

        self::assertInstanceOf(BaseStub::class, $client);
        // Contains, not equals: gRPC canonicalises the target (`dns:///localhost:50051`) in some
        // core versions.
        self::assertStringContainsString(self::DUMMY_TARGET, $client->getTarget());
    }

    public function testAServiceClientAcceptsTheHandWrittenBearerAuthenticator(): void
    {
        $authenticator = new BearerTokenAuthenticator('a-token');

        // The point of the hand-written auth surface: its output IS a valid `$opts` array for a
        // generated stub. \Grpc\BaseStub rejects a missing `credentials` key and a non-callable
        // `update_metadata`, so constructing successfully proves both.
        $client = $this->open(new SipClient(self::DUMMY_TARGET, $authenticator->channelOptions()));

        self::assertStringContainsString(self::DUMMY_TARGET, $client->getTarget());
    }

    #[DataProvider('unaryMethods')]
    public function testTheExpectedUnaryMethodsExist(string $method): void
    {
        self::assertTrue(
            method_exists(SipClient::class, $method),
            SipClient::class . '::' . $method . '() is missing from the generated stub'
        );

        $reflected = new ReflectionMethod(SipClient::class, $method);
        self::assertTrue($reflected->isPublic());
        // <request message>, array $metadata = [], array $options = []
        self::assertSame(3, $reflected->getNumberOfParameters());
        self::assertSame(1, $reflected->getNumberOfRequiredParameters());
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function unaryMethods(): iterable
    {
        foreach ([
            'SipStartSession',
            'SipEndSession',
            'SipStartCall',
            'SipEndCall',
            'SipTransferCall',
            'SipRegisterAccount',
            'SipGetSipStatus',
            'SipGetSipStatusHistory',
            'SipPlayWavFiles',
            'SipMute',
            'SipUnMute',
        ] as $method) {
            yield $method => [$method];
        }
    }

    public function testEveryGeneratedRpcIsUnary(): void
    {
        // ondewo-sip-api declares no streaming RPC. A streaming method generated by
        // grpc_php_plugin takes no request message, so a zero-required-parameter RPC on this
        // stub would mean the api grew one and this suite silently stopped covering it.
        foreach (self::unaryMethods() as [$method]) {
            $reflected = new ReflectionMethod(SipClient::class, $method);
            self::assertSame(
                1,
                $reflected->getNumberOfRequiredParameters(),
                $method . '() no longer takes a request message - is it a streaming RPC now?'
            );
        }
    }

    public function testTheGeneratedMethodSurfaceIsNotEmpty(): void
    {
        $methods = get_class_methods(SipClient::class);

        self::assertContains('SipStartSession', $methods);
        // The unary RPCs and the constructor - plus whatever \Grpc\BaseStub contributes, which is
        // why this is a lower bound rather than an equality.
        self::assertGreaterThanOrEqual(
            self::UNARY_METHOD_COUNT + 1,
            count($methods),
            'SipClient exposes fewer methods than ondewo.sip.Sip declares RPCs'
            . ' - the service proto may not have been compiled'
        );
    }

    private function open(BaseStub $client): BaseStub
    {
        $this->openClients[] = $client;

        return $client;
    }
}
